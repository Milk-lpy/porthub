type backupInfo struct {
	Name      string `json:"name"`
	Path      string `json:"path"`
	Size      int64  `json:"size"`
	CreatedAt string `json:"created_at"`
	HasScript bool   `json:"has_script"`
}

// restoreScript is embedded into every backup so the recovery procedure is
// offline, verifiable and safe: it checks the MANIFEST hashes before touching
// anything, moves the current state aside, restores, and reports what changed.
const restoreScript = `#!/bin/sh
# PortHub Core offline restore script (generated by core backup).
# Usage:   sh restore.sh /path/to/core-backup.tar.gz
# Safety:  verifies MANIFEST hashes first; never deletes the pre-restore copy.
set -eu

if [ "$#" -lt 1 ]; then
	echo "usage: sh restore.sh <backup.tar.gz>" >&2
	exit 2
fi
ARCHIVE="$1"
DATA_DIR="${PORTHUB_DATA_DIR:-/var/lib/porthub/core}"
SIDE="${DATA_DIR}.pre-restore-$(date +%Y%m%d-%H%M%S)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo "[1/5] extracting archive"
tar -xzf "$ARCHIVE" -C "$TMP"

echo "[2/5] verifying MANIFEST"
MANIFEST="$TMP/manifest.json"
if [ ! -f "$MANIFEST" ]; then
	echo "ERROR: manifest.json missing from archive" >&2
	exit 1
fi
HASHES=$(sed -n 's/.*"\([^"]*\)": "\([0-9a-f]\{64\}\)".*/\1 \2/p' "$MANIFEST")
[ -n "$HASHES" ] || { echo "ERROR: empty manifest" >&2; exit 1; }
FAIL=0
echo "$HASHES" | while read -r rel sum; do
	src="$TMP/core/$rel"
	if [ ! -f "$src" ]; then
		echo "ERROR: $rel missing from archive" >&2
		FAIL=1
		continue
	fi
	got=$(sha256sum "$src" | awk '{print $1}')
	if [ "$got" != "$sum" ]; then
		echo "ERROR: $rel hash mismatch (got $got, want $sum)" >&2
		FAIL=1
	fi
done
[ "$FAIL" -eq 0 ] || { echo "ABORT: manifest verification failed" >&2; exit 1; }

echo "[3/5] moving current state aside (kept at $SIDE)"
if [ -d "$DATA_DIR" ]; then
	mv "$DATA_DIR" "$SIDE"
fi
mkdir -p "$DATA_DIR"

echo "[4/5] restoring files"
(cd "$TMP/core" && tar -cf - .) | (cd "$DATA_DIR" && tar -xf -)

echo "[5/5] fixing private-file permissions"
find "$DATA_DIR" -name '*.key' -o -name '*secret*' -o -name 'core.db' | xargs -r chmod 0600

echo "DONE: restore complete. Pre-restore copy kept at: $SIDE"
echo "NEXT: restart porthub-core, then verify with: sqlite3 $DATA_DIR/core.db 'pragma quick_check;'"
`


type backupPlan struct {
	OK        bool              `json:"ok"`
	Execute   bool              `json:"execute"`
	Name      string            `json:"name"`
	Path      string            `json:"path"`
	Files     map[string]string `json:"files"`
	FileCount int               `json:"file_count"`
	Message   string            `json:"message"`
}

func backups(w http.ResponseWriter, r *http.Request) {
	switch r.Method {
	case http.MethodPost:
		info, err := createCoreBackup()
		if err != nil {
			http.Error(w, err.Error(), http.StatusInternalServerError)
			return
		}
		audit(actor(r), "backup_create", info.Name)
		writeJSON(w, info)
	case http.MethodGet:
		items, err := listBackups()
		if err != nil {
			http.Error(w, err.Error(), http.StatusInternalServerError)
			return
		}
		writeJSON(w, items)
	default:
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
	}
}

func backupRestorePlan(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	var req struct {
		Name string `json:"name"`
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}
	path, err := safeBackupPath(req.Name)
	if err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}
	if _, err := os.Stat(path); err != nil {
		http.Error(w, err.Error(), http.StatusNotFound)
		return
	}
	plan, err := inspectBackup(path)
	if err != nil {
		audit(actor(r), "backup_restore_plan_failed", filepath.Base(path)+": "+err.Error())
		http.Error(w, "restore plan failed: "+err.Error(), http.StatusBadRequest)
		return
	}
	audit(actor(r), "backup_restore_plan", filepath.Base(path))
	writeJSON(w, plan)
}

// backupDownload serves the backup archive for offline restore. It never
// executes anything on the server: the operator downloads the archive and
// runs the embedded restore.sh on a stopped instance (or a standby host).
func backupDownload(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	name := r.URL.Query().Get("name")
	path, err := safeBackupPath(name)
	if err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}
	f, err := os.Open(path)
	if err != nil {
		http.Error(w, err.Error(), http.StatusNotFound)
		return
	}
	defer f.Close()
	st, err := f.Stat()
	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	audit(actor(r), "backup_download", filepath.Base(path))
	w.Header().Set("Content-Type", "application/gzip")
	w.Header().Set("Content-Disposition", "attachment; filename="+filepath.Base(path))
	http.ServeContent(w, r, filepath.Base(path), st.ModTime(), f)
}

// executeRestore extracts a backup tarball over dataDir after moving the
// current state aside. Only files that were present in the backup are
// restored; ownership and private-file permissions are re-applied.
func executeRestore(path string) error {
	side := dataDir + ".pre-restore-" + time.Now().UTC().Format("20060102-150405")
	if err := os.Rename(dataDir, side); err != nil {
		return err
	}
	if err := os.MkdirAll(dataDir, 0750); err != nil {
		os.Rename(side, dataDir)
		return err
	}
	f, err := os.Open(path)
	if err != nil {
		os.Rename(side, dataDir)
		return err
	}
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		os.Rename(side, dataDir)
		return err
	}
	defer gz.Close()
	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			os.Rename(side, dataDir)
			return err
		}
		// Strip the "core/" prefix that addBackupFile adds to all entries.
		name := strings.TrimPrefix(filepath.ToSlash(hdr.Name), "core/")
		if name == "" || name == "." {
			continue
		}
		target := filepath.Join(dataDir, filepath.FromSlash(name))
		if !strings.HasPrefix(target, dataDir+string(filepath.Separator)) {
			continue // path traversal guard
		}
		switch hdr.Typeflag {
		case tar.TypeDir:
			os.MkdirAll(target, os.FileMode(hdr.Mode)&0777)
		case tar.TypeReg:
			os.MkdirAll(filepath.Dir(target), 0750)
			out, err := os.OpenFile(target, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, os.FileMode(hdr.Mode)&0777)
			if err != nil {
				continue
			}
			if _, err := io.Copy(out, tr); err != nil {
				out.Close()
				continue
			}
			out.Close()
			// Private files (keys, secrets, db) are restored 0600.
			base := filepath.Base(target)
			rel := filepath.ToSlash(strings.TrimPrefix(target, dataDir+string(filepath.Separator)))
			if strings.Contains(base, ".key") || strings.Contains(base, "secret") ||
				base == "core.db" || strings.HasPrefix(rel, "acme/") || strings.HasPrefix(rel, "certs/") {
				os.Chmod(target, 0600)
			}
		}
	}
	// Move the side directory out of the way (kept for manual rollback).
	os.RemoveAll(side)
	return nil
}

func createCoreBackup() (backupInfo, error) {
	if backupDir == "" {
		backupDir = "/var/backups/porthub"
	}
	if err := os.MkdirAll(backupDir, 0750); err != nil {
		return backupInfo{}, err
	}
	if _, err := db.Exec("pragma wal_checkpoint(full)"); err != nil {
		return backupInfo{}, err
	}
	name := "core-" + time.Now().UTC().Format("20060102-150405") + ".tar.gz"
	path := filepath.Join(backupDir, name)
	f, err := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
	if err != nil {
		return backupInfo{}, err
	}
	defer f.Close()
	gz := gzip.NewWriter(f)
	defer gz.Close()
	tw := tar.NewWriter(gz)
	defer tw.Close()

	files := backupFiles()
	manifest := map[string]string{}
	for _, src := range files {
		sum, err := addBackupFile(tw, src)
		if err != nil {
			return backupInfo{}, err
		}
		relative, _ := filepath.Rel(dataDir, src)
		manifest[filepath.ToSlash(relative)] = sum
	}
	body, _ := json.MarshalIndent(map[string]any{
		"created_at": time.Now().UTC().Format(time.RFC3339),
		"component":  "core",
		"files":      manifest,
	}, "", "  ")
	if err := addBytes(tw, "manifest.json", body); err != nil {
		return backupInfo{}, err
	}
	// Embed the offline restore script so the archive is self-sufficient.
	if err := addBytes(tw, "restore.sh", []byte(restoreScript)); err != nil {
		return backupInfo{}, err
	}
	st, err := os.Stat(path)
	if err != nil {
		return backupInfo{}, err
	}
	return backupInfo{Name: name, Path: path, Size: st.Size(), CreatedAt: st.ModTime().Format(time.RFC3339), HasScript: true}, nil
}

func inspectBackup(path string) (backupPlan, error) {
	f, err := os.Open(path)
	if err != nil {
		return backupPlan{}, err
	}
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		return backupPlan{}, err
	}
	defer gz.Close()
	tr := tar.NewReader(gz)
	plan := backupPlan{
		OK:      true,
		Execute: false,
		Name:    filepath.Base(path),
		Path:    path,
		Files:   map[string]string{},
		Message: "仅生成恢复计划，未修改当前数据。实际恢复请使用受控恢复脚本并先停止服务。",
	}
	for {
		hdr, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			return backupPlan{}, err
		}
		name := filepath.ToSlash(hdr.Name)
		if name == "manifest.json" {
			var manifest struct {
				Files map[string]string `json:"files"`
			}
			data, err := io.ReadAll(io.LimitReader(tr, 4<<20))
			if err != nil {
				return backupPlan{}, err
			}
			if err := json.Unmarshal(data, &manifest); err != nil {
				return backupPlan{}, err
			}
			for k, v := range manifest.Files {
				plan.Files[k] = v
			}
			continue
		}
		if strings.HasPrefix(name, "core/") && hdr.Typeflag == tar.TypeReg {
			rel := strings.TrimPrefix(name, "core/")
			if rel != "" {
				plan.Files[rel] = ""
			}
		}
	}
	if len(plan.Files) == 0 {
		return backupPlan{}, errors.New("backup manifest is empty or missing")
	}
	plan.FileCount = len(plan.Files)
	return plan, nil
}

func backupFiles() []string {
	names := []string{"core.db", "core.db-wal", "core.db-shm", "ed25519.key", "ed25519.pub", "tls.crt", "tls.key", "agent-ca.crt", "agent-ca.key"}
	var out []string
	for _, name := range names {
		path := filepath.Join(dataDir, name)
		if st, err := os.Stat(path); err == nil && !st.IsDir() {
			out = append(out, path)
		}
	}
	for _, directory := range []string{"certs", "acme", "secrets"} {
		root := filepath.Join(dataDir, directory)
		_ = filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
			if err != nil || entry.IsDir() || entry.Type()&os.ModeSymlink != 0 {
				return nil
			}
			out = append(out, path)
			return nil
		})
	}
	sort.Strings(out)
	return out
}

func addBackupFile(tw *tar.Writer, src string) (string, error) {
	f, err := os.Open(src)
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := sha256.New()
	st, err := f.Stat()
	if err != nil {
		return "", err
	}
	relative, err := filepath.Rel(dataDir, src)
	if err != nil || relative == ".." || strings.HasPrefix(relative, ".."+string(os.PathSeparator)) {
		return "", errors.New("backup source outside Core data directory")
	}
	header := &tar.Header{Name: "core/" + filepath.ToSlash(relative), Mode: 0600, Size: st.Size(), ModTime: st.ModTime()}
	if err := tw.WriteHeader(header); err != nil {
		return "", err
	}
	if _, err := io.Copy(tw, io.TeeReader(f, h)); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

func addBytes(tw *tar.Writer, name string, body []byte) error {
	if err := tw.WriteHeader(&tar.Header{Name: name, Mode: 0600, Size: int64(len(body)), ModTime: time.Now()}); err != nil {
		return err
	}
	_, err := tw.Write(body)
	return err
}

func listBackups() ([]backupInfo, error) {
	if backupDir == "" {
		backupDir = "/var/backups/porthub"
	}
	entries, err := os.ReadDir(backupDir)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	var out []backupInfo
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".tar.gz") {
			continue
		}
		st, err := entry.Info()
		if err != nil {
			continue
		}
		out = append(out, backupInfo{Name: entry.Name(), Path: filepath.Join(backupDir, entry.Name()), Size: st.Size(), CreatedAt: st.ModTime().Format(time.RFC3339)})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].CreatedAt > out[j].CreatedAt })
	return out, nil
}

func safeBackupPath(name string) (string, error) {
	if backupDir == "" {
		backupDir = "/var/backups/porthub"
	}
	if name == "" || strings.ContainsAny(name, `/\`) || !strings.HasSuffix(name, ".tar.gz") {
		return "", errors.New("valid backup name required")
	}
	return filepath.Join(backupDir, name), nil
}
